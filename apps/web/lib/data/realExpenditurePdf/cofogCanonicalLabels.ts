const grandTotalLabelKa = "ჯამური";

function canonicalHierarchyPath(code: string): string | null {
  const parts = code.split(".");
  const segments: string[] = [];
  for (let depth = 2; depth <= parts.length; depth += 1) {
    const ancestor = parts.slice(0, depth).join(".");
    const label = canonicalFunctionalLabelsKa.get(ancestor);
    if (!label) return null;
    segments.push(label);
  }
  return segments.join(" > ");
}

export function canonicalFunctionalLabelKa(code: string): string | null {
  return canonicalFunctionalLabelsKa.get(code) ?? null;
}

/**
 * Replace legacy-font labels with canonical ones. Rows whose functional code
 * has no canonical label keep their original text; rawRowText always keeps the
 * original extracted evidence.
 */
export function canonicalizeExpenditurePdfRowLabels(rows: ExpenditurePdfOfficialRow[]): ExpenditurePdfOfficialRow[] {
  return rows.map((row) => {
    if (row.rowType === "grand_total") {
      return { ...row, labelKa: grandTotalLabelKa, hierarchyPath: grandTotalLabelKa };
    }
    if (!row.functionalCode) return row;
    const labelKa = canonicalFunctionalLabelsKa.get(row.functionalCode);
    const hierarchyPath = canonicalHierarchyPath(row.functionalCode);
    if (!labelKa || !hierarchyPath) return row;
    return { ...row, labelKa, hierarchyPath };
  });
}
